    voltaje = (float)adc1_codigo[0] * 3.3f / 4095.0f; 
    bateria = (float)adc1_codigo[1] * 3.3f / 4095.0f * 4.0f; // Ajuste divisor de voltaje

    // 2. Disparo y lectura del sensor ultrasónico HC-SR04
    sr04_trigger(&sr04);
    distancia_cm = sr04.distance / 10; // De mm a cm

    // 3. Transmisión serial por UART1
    sprintf(buffer, "Voltaje: %.2f V | Bateria: %.2f V | Distancia: %lu cm\r\n", 
            voltaje, bateria, (unsigned long)distancia_cm);
